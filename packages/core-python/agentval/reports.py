"""Human- and machine-readable reports: Markdown (PR comments, wikis), CSV (spreadsheets), JSON."""

from __future__ import annotations

import csv
import io
from typing import Any


def _pct(v: Any) -> str:
    return "n/a" if v is None else f"{float(v):.0%}"


def _num(v: Any, digits: int = 3) -> str:
    return "n/a" if v is None else f"{float(v):.{digits}f}"


def _ci(ci: Any, pct: bool = False) -> str:
    if not ci or len(ci) != 2:
        return ""
    lo, hi = ci
    return f" (95% CI {_pct(lo)}-{_pct(hi)})" if pct else f" (95% CI {_num(lo)}-{_num(hi)})"


def run_markdown(run: dict[str, Any]) -> str:
    """Markdown report for a run (``RunDetail`` JSON, camelCase)."""
    m = run.get("metrics") or {}
    lines = [
        f"# AgentVal report: {run.get('name')}",
        "",
        f"- **Dataset:** {run.get('datasetName') or run.get('datasetId')}",
        f"- **Model:** `{run.get('model')}`",
        f"- **Status:** {run.get('status')}  ",
        f"- **Created:** {run.get('createdAt')}",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Pass rate | {_pct(m.get('passRate'))}{_ci(m.get('passRateCi'), pct=True)} |",
        f"| Avg score | {_num(m.get('avgScore'))}{_ci(m.get('avgScoreCi'))} |",
        f"| Pass / partial / fail / error | {m.get('passed', 0)} / {m.get('partial', 0)} / {m.get('failed', 0)} / {m.get('errored', 0)} |",
        f"| Avg latency (p95) | {_num(m.get('avgLatencyMs'), 0)} ms ({_num(m.get('p95LatencyMs'), 0)} ms) |",
        f"| Tokens | {m.get('tokenCount', 0):,} |",
        f"| Cost | ${float(m.get('totalCostUsd') or 0):.6f} |",
    ]
    if (m.get("trials") or 1) > 1:
        lines += [f"| Trials per case | {m['trials']} |",
                  f"| pass@k / pass^k | {_pct(m.get('passAtK'))} / {_pct(m.get('passHatK'))} |",
                  f"| Consistency | {_pct(m.get('consistency'))} |"]
    if m.get("scorerAverages"):
        lines += ["", "## Scorers", "", "| Scorer | Avg |", "| --- | --- |"]
        lines += [f"| {k} | {_num(v)} |" for k, v in m["scorerAverages"].items()]
    if m.get("tagBreakdown"):
        lines += ["", "## By tag", "", "| Tag | Cases | Pass rate | Avg score |", "| --- | --- | --- | --- |"]
        lines += [f"| {k} | {v['n']} | {_pct(v['passRate'])} | {_num(v['avgScore'])} |" for k, v in m["tagBreakdown"].items()]
    results = run.get("results") or []
    if results:
        lines += ["", "## Test cases", "", "| Case | Trial | Status | Score | Latency | Notes |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for r in results:
            notes = "; ".join(f"{k}: {v.get('rationale', '')}" for k, v in (r.get("scores") or {}).items()
                              if not v.get("skipped") and v.get("score", 1) < 1)
            notes = notes.replace("|", "\\|").replace("\n", " ")[:220]
            lines.append(f"| {r.get('testCaseName')} | {r.get('trial', 0) + 1} | {r.get('status')} | "
                         f"{_num(r.get('score'))} | {r.get('latencyMs')} ms | {notes or '-'} |")
    lines += ["", "_Generated by [AgentVal](https://github.com/shanakiraj/AgentVal)._", ""]
    return "\n".join(lines)


def run_csv(run: dict[str, Any]) -> str:
    buf = io.StringIO()
    scorer_names = sorted({k for r in run.get("results") or [] for k in (r.get("scores") or {})})
    w = csv.writer(buf)
    w.writerow(["test_case", "trial", "status", "score", "passed", "latency_ms", "prompt_tokens", "completion_tokens",
                "cost_usd", "attempts", *[f"score_{s}" for s in scorer_names], "error"])
    for r in run.get("results") or []:
        sc = r.get("scores") or {}
        w.writerow([r.get("testCaseName"), r.get("trial", 0), r.get("status"), r.get("score"), r.get("passed"),
                    r.get("latencyMs"), r.get("promptTokens"), r.get("completionTokens"), r.get("costUsd"),
                    r.get("attempts"),
                    *[("" if (sc.get(s) or {}).get("skipped") else (sc.get(s) or {}).get("score", "")) for s in scorer_names],
                    r.get("error") or ""])
    return buf.getvalue()


VERDICT_LABEL = {
    "regression": "Statistically significant regression",
    "improvement": "Statistically significant improvement",
    "possible_regression": "Possible regression (not significant)",
    "possible_improvement": "Possible improvement (not significant)",
    "no_significant_change": "No significant change",
    "inconclusive": "Inconclusive (no paired cases)",
}


def _p(v: float) -> str:
    return "< 0.001" if v < 0.001 else f"{v:.3f}"


def compare_markdown(name_a: str, name_b: str, regression: dict[str, Any]) -> str:
    s, g = regression["summary"], regression["gate"]
    lines = [
        f"## AgentVal regression check: {'PASSED' if g['passed'] else 'FAILED'}",
        "",
        f"**Baseline (A):** {name_a}  ",
        f"**Candidate (B):** {name_b}",
        "",
        f"**Verdict:** {VERDICT_LABEL.get(s['verdict'], s['verdict'])}",
        "",
        "| | |",
        "| --- | --- |",
        f"| Mean case score delta | {s['meanDelta']:+.3f} (95% CI {s['ci95'][0]:+.3f} to {s['ci95'][1]:+.3f}) |",
        f"| Paired bootstrap p | {_p(s['pValue'])} |",
        f"| Pass->fail / fail->pass | {s['newFailures']} / {s['newPasses']} (McNemar p {_p(s['mcnemarP'])}) |",
        f"| Improved / regressed / unchanged | {s['improved']} / {s['regressed']} / {s['unchanged']} |",
    ]
    if g["reasons"]:
        lines += ["", "**Gate failures:**", *[f"- {r}" for r in g["reasons"]]]
    moved = [c for c in regression["cases"] if c["change"] in {"improved", "regressed"}]
    if moved:
        lines += ["", "| Case | A | B | Delta |", "| --- | --- | --- | --- |"]
        for c in sorted(moved, key=lambda c: c["delta"]):
            icon = "🔻" if c["change"] == "regressed" else "🔺"
            lines.append(f"| {icon} {c['testCaseName']} | {c['statusA']} {c['scoreA']:.3f} | {c['statusB']} "
                         f"{c['scoreB']:.3f} | {c['delta']:+.3f} |")
    return "\n".join(lines) + "\n"
